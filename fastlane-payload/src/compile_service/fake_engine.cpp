class FakeEngine : public CompileEngine {
public:
    EngineResult compile(const EngineRequest& request) override {
        EngineResult result;
        if (request.source.empty()) {
            result.status = JobStatus::kCompileError;
            result.diagnostics = "fake engine: empty preprocessed input\n";
            return result;
        }
        if (request.cancel != nullptr && request.cancel->cancelled.load()) {
            result.status = JobStatus::kJobTimeout;
            return result;
        }
        result.status = JobStatus::kOk;
        result.object.assign(kFixedObject.begin(), kFixedObject.end());
        return result;
    }

    std::string compiler_version() const override { return "fake-engine 1"; }
};

std::unique_ptr<CompileEngine> make_fake_engine() {
    return std::make_unique<FakeEngine>();
}

